"""Builds server/nobility-fiefs.json, the fiefs of the nobility system (nobility.js; docs/nobility/DESIGN.md).

A fief is a real town (Nate, 10 Oct). Each one is named here by the LCTN record of the town (its editor id), and the
plugins say the rest: the town's exterior cells are the worldspace cells whose XLCN is that location, and its buildings are
the buildings of buildings.json whose way in stands in one of those cells. A building's cells are the fief's interior cells.
Dungeon buildings (buildings.json flag "dungeon") are never part of a fief, and a building whose LCTN names the town but whose
door stands elsewhere is left out and listed (Bleak Frost Mine's names Mountain Watch and stands near Applewatch).
The town's county is the LCTN parent the plugins give it (Beyond Skyrim puts Aleswell in the Heartlands and Mountain Watch in
Cheydinhal County); the hold a fief answers to is Nate's choice, kept in FIEFS below.

Runs on the dev server (plugins in /opt/skyrim-data) or on the PC, with the ck-mcp parser:
    python3 tools/nobility_fiefs.py [--data DIR] [--order FILE] [--ck-mcp DIR] [--out FILE] [--check] [--towns]
--check exits 1 if the file differs; --towns also prints every town-like location of the fiefs' worldspaces (LocTypeTown,
LocTypeCity, LocTypeSettlement, LocTypeHabitation) for review. Run it with nice on the live box."""
import sys, os, json, struct, argparse, math

HERE = os.path.dirname(os.path.abspath(__file__))
SERVER = os.path.dirname(HERE)
ROOT = os.path.dirname(SERVER)
ap = argparse.ArgumentParser()
ap.add_argument('--data', default='/opt/skyrim-data' if os.path.isdir('/opt/skyrim-data') else os.path.join(ROOT, 'Skyrim Special Edition - dev', 'Data'))
ap.add_argument('--order', default=os.path.join(SERVER, 'plugins.server.txt'))
CKMCP = [os.path.join(ROOT, 'ck-mcp'), os.path.expanduser('~/dragonbreak/ck-mcp'), os.path.join(SERVER, 'tooling', 'ck-mcp')]
ap.add_argument('--ck-mcp', dest='ckmcp', default=next((d for d in CKMCP if os.path.isdir(d)), CKMCP[0]))
ap.add_argument('--out', default=os.path.join(SERVER, 'nobility-fiefs.json'))
ap.add_argument('--check', action='store_true')
ap.add_argument('--towns', action='store_true')
args = ap.parse_args()
sys.path.insert(0, args.ckmcp)
import core

# Nate, 10 Oct: the fiefs around Bruma. id -> (display name, LCTN editor id, the hold that grants it)
FIEFS = {
    'applewatch': ('Applewatch', 'CYRApplewatchLocation', 'bruma'),
    'aleswell': ('Aleswell', 'CYRAleswellLocation', 'bruma'),
    'mountain-watch': ('Mountain Watch', 'CYRMountainwatchLocation', 'bruma'),
}
CELL = 4096
TOWNISH = ('LocTypeTown', 'LocTypeCity', 'LocTypeSettlement', 'LocTypeHabitation')

lo = core.LoadOrder(args.data, args.order)
if lo.missing_plugins: print("missing plugins:", lo.missing_plugins)
def desc(canon):
    src, loc = canon.rsplit(':', 1)
    return "%x:%s" % (int(loc, 16), src)
def canon_of(d):
    loc, src = d.split(':', 1)
    return "%s:%06X" % (src, int(loc, 16))
def chain(l):
    out = []
    while l and l in locs and len(out) < 10: out.append(l); l = locs[l]['parent']
    return out
def ref(p, raw, n=4):
    return lo.canon(p, struct.unpack("<I", raw[:4])[0]) if len(raw) >= n else None

kywd, locs, cells = {}, {}, {}
for p in lo.plugins:
    for ri, t, fid, fl, off, sz, ctx in lo.records(p, ('KYWD', 'LCTN', 'CELL')):
        c = lo.canon(p, fid)
        e = core.esplib.edid_of(lo.body(p, off, sz, fl)) or ''
        sub = lo.subrecords(p, off, sz, fl)
        if t == 'KYWD':
            kywd[c] = e
        elif t == 'LCTN':
            kw = sub.get(b'KWDA', b'')
            locs[c] = {'edid': e, 'kw': [lo.canon(p, struct.unpack_from('<I', kw, i)[0]) for i in range(0, len(kw) - 3, 4)], 'parent': ref(p, sub.get(b'PNAM', b''))}
        else:
            w = ctx[0]; xc = sub.get(b'XCLC', b''); prev = cells.get(c, {})
            cells[c] = {'edid': e or prev.get('edid', ''), 'loc': ref(p, sub.get(b'XLCN', b'')) or prev.get('loc'),
                        'world': lo.canon(p, w) if w else prev.get('world'), 'grid': list(struct.unpack('<ii', xc[:8])) if len(xc) >= 8 else prev.get('grid')}
for L in locs.values(): L['kw'] = [kywd.get(k, '?') for k in L['kw']]
by_edid = {L['edid']: c for c, L in locs.items()}

buildings = json.load(open(os.path.join(SERVER, 'buildings.json'), encoding='utf-8'))['buildings']
doors = json.load(open(os.path.join(SERVER, 'doors-pos.json'), encoding='utf-8'))['doors']

out = {'_comment': 'Generated by server/tools/nobility_fiefs.py from the load order, buildings.json and doors-pos.json; do not edit, change FIEFS there. A fief is a real town: grid lists its exterior cells [x, y] (cell = 4096 units) in its world, cells the interior cells of its buildings (mp descs). nobility.js answers which fief a reference stands in from these; county is the LCTN parent the plugins give the town.',
       'fiefs': []}
skipped = []
for fid, (name, edid, hold) in FIEFS.items():
    loc = by_edid.get(edid)
    if not loc: print('no LCTN', edid); continue
    ext = sorted(C['grid'] for C in cells.values() if C.get('world') and C.get('loc') == loc and C.get('grid'))
    worlds = sorted({C['world'] for C in cells.values() if C.get('world') and C.get('loc') == loc})
    if len(worlds) != 1: print('fief', fid, 'spans worlds', worlds); continue
    world = desc(worlds[0])
    fb, fcells = [], set()
    for b in buildings:
        if b.get('world') != world: continue
        grids = [[math.floor(doors[e['door']][0] / CELL), math.floor(doors[e['door']][1] / CELL)] for e in b.get('entrances', []) if e.get('door') in doors]
        names_town = any(loc in chain(cells.get(canon_of(c), {}).get('loc')) for c in b['cells'])
        inside = any(g in ext for g in grids)
        if inside and 'dungeon' in (b.get('flags') or []): skipped.append((fid, b['name'], 'dungeon')); continue
        if not inside:
            if names_town: skipped.append((fid, b['name'], 'its door stands outside the town'))
            continue
        fb.append({'id': b['id'], 'name': b['name'], 'doors': [e['door'] for e in b.get('entrances', [])]})
        fcells.update(b['cells'])
    cx = sum(g[0] * CELL + CELL / 2 for g in ext) / len(ext); cy = sum(g[1] * CELL + CELL / 2 for g in ext) / len(ext)
    out['fiefs'].append({'id': fid, 'name': name, 'hold': hold, 'location': desc(loc), 'edid': edid,
                         'county': locs.get(locs[loc]['parent'], {}).get('edid', ''), 'world': world, 'center': [round(cx), round(cy)],
                         'grid': ext, 'cells': sorted(fcells), 'buildings': sorted(fb, key=lambda x: x['name'])})
for s in skipped: print('left out of %s: %s (%s)' % s)

if args.towns:
    worlds = {f['world'] for f in out['fiefs']}
    for c, L in sorted(locs.items(), key=lambda x: x[1]['edid']):
        if not any(k in L['kw'] for k in TOWNISH): continue
        g = [C['grid'] for C in cells.values() if C.get('loc') == c and C.get('world') and desc(C['world']) in worlds]
        if g: print('town-like: %s %s parent %s, %d cells near %s' % (L['edid'], [k for k in L['kw'] if k.startswith('LocType')], locs.get(L['parent'], {}).get('edid'), len(g), g[0]))

text = json.dumps(out, indent=1) + '\n'
if args.check:
    old = open(args.out, encoding='utf-8').read() if os.path.exists(args.out) else ''
    print('current' if old == text else 'differs'); sys.exit(0 if old == text else 1)
open(args.out, 'w', encoding='utf-8', newline='\n').write(text)
print('wrote', args.out, [(f['id'], len(f['buildings'])) for f in out['fiefs']])
