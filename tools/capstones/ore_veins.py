"""Every ore vein in a load order, for the Grandmaster Miner's Prospector's Sense (capstones.js, Nat 2 Nov).

Writes { "veins": [{ "edid", "world", "pos" }] }: each placed REFR whose base editor id starts with MineOre, in its
winning override, with its worldspace (exteriors) or interior cell as the server spells a desc ("3c:Skyrim.esm").
Deleted and initially disabled references are left out: the server never loads them, so nobody could mine them.
The positions come from the plugins, so the output is Bethesda-derived data: it goes to ore-veins.private.json beside
the server (gitignored by *.private.json) and is delivered with deploy-private, never committed.

usage: python3 ore_veins.py <data dir> <load order file, one plugin a line> <out.json> [esplib dir]
       esplib is ck-mcp/esplib.py; pass its folder when it is not beside this script.
"""
import sys, os, json, struct

data_dir, lo_file, out_file = sys.argv[1:4]
sys.path.insert(0, sys.argv[4] if len(sys.argv) > 4 else os.path.dirname(os.path.abspath(__file__)))
import esplib

DELETED, DISABLED = 0x20, 0x800
names = [l.strip().lstrip('*') for l in open(lo_file, encoding='utf-8', errors='replace') if l.strip() and not l.startswith('#')]
spelled = {os.path.basename(n).lower(): os.path.basename(n) for n in names}
plugins = [esplib.Plugin(os.path.join(data_dir, os.path.basename(n))) for n in names if os.path.exists(os.path.join(data_dir, os.path.basename(n)))]

def desc(src, local):
    return '%x:%s' % (local, spelled.get(src, src))

bases = {}   # (src, local) -> editor id, for MineOre* bases
for pl in plugins:
    with open(pl.path, 'rb') as fh:
        for sig, fid, flags, off, size, ctx in pl.index:
            if sig not in ('ACTI', 'MSTT', 'STAT'):
                continue
            e = esplib.edid_of(pl.data_at(fh, off, size, flags))
            if e and e.lower().startswith('mineore'):
                bases[pl.modindex_source(fid)] = e

refs = {}    # (src, local) of the REFR -> its winning record, the last plugin's
for pl in plugins:
    with open(pl.path, 'rb') as fh:
        for sig, fid, flags, off, size, ctx in pl.index:
            if sig != 'REFR':
                continue
            d = pl.data_at(fh, off, size, flags)
            base = pos = None
            for s, v in esplib.subrecords(d):
                if s == b'NAME':
                    base = pl.modindex_source(struct.unpack('<I', v[:4])[0])
                elif s == b'DATA' and len(v) >= 12:
                    pos = struct.unpack('<3f', v[:12])
            key = pl.modindex_source(fid)
            if base not in bases and key not in refs:
                continue
            w, c, g = ctx
            where = pl.modindex_source(w) if w else pl.modindex_source(c)
            refs[key] = (flags, base, pos, where)

veins = []
for key, (flags, base, pos, where) in refs.items():
    if flags & (DELETED | DISABLED) or base not in bases or not pos or not where[0]:
        continue
    veins.append({'edid': bases[base], 'world': desc(*where), 'pos': [round(x, 1) for x in pos]})
veins.sort(key=lambda v: (v['world'], v['edid']))
json.dump({'_comment': 'Generated by tools/capstones/ore_veins.py over the live load order. Bethesda-derived: never commit.', 'veins': veins}, open(out_file, 'w'), indent=0)
print('%d veins in %d worlds and cells, %d vein bases' % (len(veins), len({v['world'] for v in veins}), len(bases)))
