'use strict'
// sources/securityHeaders.js and its place in server.js: nosniff on every answer, CSP sandbox on the extra files (console review B6)

const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const http = require('http')
const os = require('os')
const path = require('path')

test('nosniff on every backend answer, and CSP sandbox on the extra files served on the website origin', async () => {
  const express = require('express')
  const headers = require('../sources/securityHeaders')
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dbo-console-headers-'))
  fs.writeFileSync(path.join(dir, 'page.html'), '<script>alert(1)</script>')
  const app = express()
  app.use(headers.nosniff)
  app.use('/api/files/extra', headers.sandboxed)
  app.use('/api/files/extra', express.static(dir))
  app.get('/api/x', (_req, res) => res.json({ ok: true }))
  const server = http.createServer(app)
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const get = url => new Promise(resolve => http.get(`http://127.0.0.1:${server.address().port}${url}`, { agent: false }, res => { res.resume(); res.on('end', () => resolve(res.headers)) }))
  const json = await get('/api/x'), file = await get('/api/files/extra/page.html')
  server.close(); fs.rmSync(dir, { recursive: true, force: true })
  assert.equal(json['x-content-type-options'], 'nosniff')
  assert.equal(file['x-content-type-options'], 'nosniff')
  assert.equal(file['content-security-policy'], 'sandbox')
  assert.equal(json['content-security-policy'], undefined)
  const src = fs.readFileSync(path.join(__dirname, '..', 'server.js'), 'utf8')
  assert.ok(src.indexOf('app.use(securityHeaders.nosniff)') < src.indexOf('app.use(cors('), 'nosniff comes before every route')
  assert.ok(src.indexOf("app.use('/api/files/extra', securityHeaders.sandboxed)") < src.indexOf("app.use('/api/files/extra', require('./sources/r2Files').extraRedirect)"))
})
